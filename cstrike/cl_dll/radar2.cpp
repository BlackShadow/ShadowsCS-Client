// Every floor height the built layout can compare against the viewer's height (sorted, no repeats). The rendered
// layout depends on the viewer's height only through "floor height <= feet + OVERVIEW_VIEWER_SLACK", so when no
// height lies between the old and the new limit it would come out exactly the same.
static std::vector<float> g_LayoutHeights;

static void CollectLayoutHeights()
{
	g_LayoutHeights.clear();
	if ( g_Map.havePicture )
	{
		// heights are 16-bit whole numbers: mark which ones occur
		std::vector<bool> used( 65536, false );
		for ( int16_t z : g_Map.picture.z )
		{
			if ( z != OVERVIEW_PIC_NONE )
				used[(size_t)( z + 32768 )] = true;
		}
		for ( size_t i = 0; i < used.size(); i++ )
		{
			if ( used[i] )
				g_LayoutHeights.push_back( static_cast<float>( static_cast<int>( i ) - 32768 ) );
		}
	}
	else
	{
		for ( float z : g_Map.layers.z )
		{
			if ( !( z <= OVERVIEW_NO_FLOOR * 0.5f ) )
				g_LayoutHeights.push_back( z );
		}
		std::sort( g_LayoutHeights.begin(), g_LayoutHeights.end() );
		g_LayoutHeights.erase( std::unique( g_LayoutHeights.begin(), g_LayoutHeights.end() ), g_LayoutHeights.end() );
	}
}

// true when some floor height h has (h <= limitA) != (h <= limitB)
static bool LayoutHeightBetween( float limitA, float limitB )
{
	const float low = limitA < limitB ? limitA : limitB;
	const float high = limitA < limitB ? limitB : limitA;
	auto it = std::upper_bound( g_LayoutHeights.begin(), g_LayoutHeights.end(), low );
	return it != g_LayoutHeights.end() && *it <= high;
}

