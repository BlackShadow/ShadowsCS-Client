static bool FindSpriteRecord( const char* list, const char* name, int res, client_sprite_t* out )
{
	int count = 0;
	client_sprite_t* recs = gHUD.GetTierSpriteList( list, &count );
	for ( int i = 0; recs && i < count; i++ )
	{
		if ( recs[i].iRes == res && !strcmp( recs[i].szName, name ) )
		{
			*out = recs[i];
			return true;
		}
	}
	return false;
}

static void LoadHudIcon( C4Icon& icon, const char* name )
{
	if ( icon.tried )
		return;
	icon.tried = true;
	client_sprite_t rec;
	const int tier = gHUD.m_iRes;
	char list[64];
	snprintf( list, sizeof( list ), "sprites/cs%d/hud.txt", tier );
	if ( ( tier <= 640 || !FindSpriteRecord( list, name, tier, &rec ) ) && !FindSpriteRecord( "sprites/hud.txt", name, 640, &rec ) )
		return;
	char path[128];
	snprintf( path, sizeof( path ), "sprites/%s.spr", rec.szSprite );
	int len = 0;
	unsigned char* f = (unsigned char*)gEngfuncs.COM_LoadFile( path, 5, &len );
	if ( !f )
		return;
	do
	{
		if ( len < 42 || memcmp( f, "IDSP", 4 ) || I32( f + 4 ) != 2 )
			break;
		const int palCount = (short)U16( f + 40 );
		if ( palCount < 1 || palCount > 256 || 42 + palCount * 3 + 20 > len )
			break;
		const unsigned char* pal = f + 42;
		const unsigned char* frame = pal + palCount * 3;
		const int fw = I32( frame + 12 ), fh = I32( frame + 16 );
		const unsigned char* pix = frame + 20;
		if ( I32( frame ) != 0 || fw <= 0 || fh <= 0 || (long long)fw * fh > ( f + len ) - pix )
			break;
		const int left = rec.rc.left, top = rec.rc.top;
		const int w = rec.rc.right - rec.rc.left, h = rec.rc.bottom - rec.rc.top;
		if ( left < 0 || top < 0 || w <= 0 || h <= 0 || left + w > fw || top + h > fh )
			break;
		// additive HUD art: brightness becomes coverage, colour is kept
		std::vector<unsigned char> rgba( (size_t)w * h * 4 );
		for ( int y = 0; y < h; y++ )
		{
			for ( int x = 0; x < w; x++ )
			{
				const unsigned char* c = pal + pix[(size_t)( top + y ) * fw + left + x] * 3;
				int a = c[0] > c[1] ? c[0] : c[1];
				a = a > c[2] ? a : c[2];
				unsigned char* d = &rgba[( (size_t)y * w + x ) * 4];
				d[0] = (unsigned char)( a ? c[0] * 255 / a : 0 );
				d[1] = (unsigned char)( a ? c[1] * 255 / a : 0 );
				d[2] = (unsigned char)( a ? c[2] * 255 / a : 0 );
				d[3] = (unsigned char)a;
			}
		}
		PadPremultiplied( rgba.data(), w, h, false, &icon.texW, &icon.texH, icon.rgba );
		icon.w = w;
		icon.h = h;
	} while ( false );
	gEngfuncs.COM_FreeFile( f );
}

