struct OverviewInfo
{
	float zoom = 1.0f;
	float origin[3] = { 0, 0, 0 };
	int rotated = 0;
	char image[128] = "";
	bool generated = false;
	bool current = false; // generated by this version
};

static bool ReadOverviewTxt( const char* map, OverviewInfo& info )
{
	char path[160];
	snprintf( path, sizeof( path ), "overviews/%s.txt", map );
	int len = 0;
	unsigned char* f = (unsigned char*)gEngfuncs.COM_LoadFile( path, 5, &len );
	if ( !f )
		return false;
	std::vector<char> text( (size_t)len + 1, 0 );
	memcpy( text.data(), f, (size_t)len );
	gEngfuncs.COM_FreeFile( f );
	info.generated = strstr( text.data(), kGeneratedMarker ) != NULL;
	info.current = info.generated && strstr( text.data(), kGeneratedVersion ) != NULL;
	char token[1024];
	char* p = text.data();
	while ( ( p = gEngfuncs.COM_ParseFile( p, token ) ) != NULL )
	{
		if ( !stricmp( token, "ZOOM" ) )
		{
			p = gEngfuncs.COM_ParseFile( p, token );
			info.zoom = (float)atof( token );
		}
		else if ( !stricmp( token, "ORIGIN" ) )
		{
			for ( int i = 0; i < 3 && p; i++ )
			{
				p = gEngfuncs.COM_ParseFile( p, token );
				info.origin[i] = (float)atof( token );
			}
		}
		else if ( !stricmp( token, "ROTATED" ) )
		{
			p = gEngfuncs.COM_ParseFile( p, token );
			info.rotated = atoi( token ) != 0;
		}
		else if ( !stricmp( token, "IMAGE" ) )
		{
			p = gEngfuncs.COM_ParseFile( p, token );
			if ( !info.image[0] )
			{
				strncpy( info.image, token, sizeof( info.image ) - 1 );
				info.image[sizeof( info.image ) - 1] = 0;
			}
		}
		if ( !p )
			break;
	}
	if ( info.zoom < 0.01f )
		info.zoom = 1.0f;
	return true;
}

// world X/Y of the corners of an overview picture (same placement as the spectator overview)
static void OverviewCorners( const OverviewInfo& o, float corner[4][2] )
{
	const float aspect = 4.0f / 3.0f;
	const float a = 4096.0f / o.zoom, b = 4096.0f / ( o.zoom * aspect );
	const float ox = o.origin[0], oy = o.origin[1];
	if ( o.rotated )
	{
		// u: X from ox-a to ox+a, v: Y from oy+b down to oy-b
		const float c[4][2] = { { ox - a, oy + b }, { ox + a, oy + b }, { ox + a, oy - b }, { ox - a, oy - b } };
		memcpy( corner, c, sizeof( c ) );
	}
	else
	{
		// u: Y from oy+a down to oy-a, v: X from ox+b down to ox-b
		const float c[4][2] = { { ox + b, oy + a }, { ox + b, oy - a }, { ox - b, oy - a }, { ox - b, oy + a } };
		memcpy( corner, c, sizeof( c ) );
	}
}

static std::string GameDirPath()
{
#ifdef _WIN32
	char exe[MAX_PATH];
	const DWORD n = GetModuleFileNameA( NULL, exe, sizeof( exe ) );
	if ( n == 0 || n >= sizeof( exe ) )
		return gEngfuncs.pfnGetGameDirectory();
	std::string dir( exe );
	const size_t slash = dir.find_last_of( "\\/" );
	dir = slash == std::string::npos ? std::string() : dir.substr( 0, slash + 1 );
	return dir + gEngfuncs.pfnGetGameDirectory();
#else
	return gEngfuncs.pfnGetGameDirectory();
#endif
}

static bool WriteFileBytes( const std::string& path, const void* data, size_t size )
{
	FILE* fp = fopen( path.c_str(), "wb" );
	if ( !fp )
		return false;
	const bool ok = fwrite( data, 1, size, fp ) == size;
	return fclose( fp ) == 0 && ok;
}

// saves the generated layout as a classic overview (only when the map has none, or an older one of ours)
static void SaveClassicOverview( const char* map, const OverviewLayers& layers, const OverviewPicture* picture )
{
	std::vector<unsigned char> bmp;
	float zoom = 1.0f, origin[3] = { 0, 0, 0 };
	int rotated = 0;
	const bool made = picture ? Overview_MakeClassicPicture( *picture, bmp, zoom, origin, rotated ) : false;
	if ( !made && ( !Overview_MakeClassic( layers, bmp, zoom, origin, rotated ) || bmp.empty() ) )
		return;
	const std::string dir = GameDirPath() + "/overviews";
#ifdef _WIN32
	CreateDirectoryA( dir.c_str(), NULL );
#endif
	char txt[1024];
	snprintf( txt, sizeof( txt ),
		"// overview description file for %s.bsp\n%s\n%s\n\nglobal\n{\n\tZOOM\t%.2f\n\tORIGIN\t%.0f\t%.0f\t%.0f\n\tROTATED\t%d\n}\n\n"
		"layer\n{\n\tIMAGE\t\"overviews/%s.bmp\"\n\tHEIGHT\t%.0f\n}\n",
		map, kGeneratedMarker, made ? kGeneratedVersion : "", zoom, origin[0], origin[1], origin[2], rotated, map, origin[2] );
	const bool okImage = WriteFileBytes( dir + "/" + map + ".bmp", bmp.data(), bmp.size() );
	const bool okText = okImage && WriteFileBytes( dir + "/" + map + ".txt", txt, strlen( txt ) );
	if ( okImage && okText )
		gEngfuncs.Con_Printf( "Radar: no overview for %s, built one from the map and saved overviews/%s.bmp/.txt\n", map, map );
	else
		gEngfuncs.Con_Printf( "Radar: could not save overviews/%s.bmp/.txt\n", map );
}

// game file loader for the map's texture WADs
static bool LoadGameFile( const char* path, std::vector<unsigned char>& data, void* )
{
	int len = 0;
	unsigned char* f = (unsigned char*)gEngfuncs.COM_LoadFile( (char*)path, 5, &len );
	if ( !f )
		return false;
	if ( len > 0 )
		data.assign( f, f + len );
	gEngfuncs.COM_FreeFile( f );
	return len > 0;
}

static void FreeMap()
{
	g_Map.upload.clear();
	g_Map.upload.shrink_to_fit();
	g_Map.layers = OverviewLayers();
	g_Map.picture = OverviewPicture();
	g_Map.havePicture = false;
	g_LayoutHeights.clear();
	g_LayoutHeights.shrink_to_fit();
	g_Map.mode = MAP_NONE;
	g_Map.needUpload = g_Map.uploaded = g_Map.layerBuilt = false;
}

static void LoadMapFor( const char* level )
{
	FreeMap();
	strncpy( g_Map.level, level, sizeof( g_Map.level ) - 1 );
	g_Map.level[sizeof( g_Map.level ) - 1] = 0;

	// "maps/de_dust2.bsp" -> "de_dust2"
	char map[96];
	const char* base = strrchr( level, '/' );
	base = base ? base + 1 : level;
	strncpy( map, base, sizeof( map ) - 1 );
	map[sizeof( map ) - 1] = 0;
	char* dot = strrchr( map, '.' );
	if ( dot )
		*dot = 0;
	if ( !map[0] )
		return;

	OverviewInfo info;
	const bool haveTxt = ReadOverviewTxt( map, info );
	if ( haveTxt && !info.generated && info.image[0] )
	{
		int w = 0, h = 0;
		const char* ext = strrchr( info.image, '.' );
		unsigned char* rgba = ext && !stricmp( ext, ".tga" ) ? VisMods_LoadTGA( info.image, &w, &h ) : LoadBMP( info.image, &w, &h );
		if ( rgba )
		{
			PadPremultiplied( rgba, w, h, true, &g_Map.texW, &g_Map.texH, g_Map.upload );
			free( rgba );
			g_Map.imgW = w;
			g_Map.imgH = h;
			OverviewCorners( info, g_Map.corner );
			g_Map.mode = MAP_IMAGE;
			g_Map.needUpload = true;
			return;
		}
	}

	// no usable overview: build the layout from the map itself
	int len = 0;
	unsigned char* bsp = (unsigned char*)gEngfuncs.COM_LoadFile( (char*)level, 5, &len );
	if ( !bsp )
		return;
	char err[256] = "";
	const bool ok = Overview_BuildLayers( bsp, len, 512, 6, g_Map.layers, err, sizeof( err ) );
	if ( !ok || g_Map.layers.w <= 0 || g_Map.layers.h <= 0 )
	{
		gEngfuncs.COM_FreeFile( bsp );
		gEngfuncs.Con_Printf( "Radar: could not build a layout for %s (%s)\n", map, err );
		g_Map.layers = OverviewLayers();
		return;
	}
	// the map seen from above with its own textures and light (like dev_overview)
	g_Map.havePicture = Overview_BuildPicture( bsp, len, g_Map.layers, 1024, LoadGameFile, NULL, g_Map.picture, err, sizeof( err ) );
	gEngfuncs.COM_FreeFile( bsp );
	if ( !g_Map.havePicture )
	{
		gEngfuncs.Con_Printf( "Radar: no map picture for %s (%s), using the plain layout\n", map, err );
		g_Map.picture = OverviewPicture();
	}
	else if ( g_Map.picture.missingTextures > 0 )
		gEngfuncs.Con_Printf( "Radar: %d texture(s) of %s not found (shown grey)\n", g_Map.picture.missingTextures, map );

	const OverviewLayers& L = g_Map.layers;
	if ( g_Map.havePicture )
	{
		const OverviewPicture& P = g_Map.picture;
		g_Map.imgW = P.w;
		g_Map.imgH = P.h;
		const float x1 = P.x0 + P.w * P.unit, y1 = P.y0 - P.h * P.unit;
		const float c[4][2] = { { P.x0, P.y0 }, { x1, P.y0 }, { x1, y1 }, { P.x0, y1 } };
		memcpy( g_Map.corner, c, sizeof( c ) );
	}
	else
	{
		g_Map.imgW = L.w;
		g_Map.imgH = L.h;
		const float x1 = L.x0 + L.w * L.cell, y1 = L.y0 - L.h * L.cell;
		const float c[4][2] = { { L.x0, L.y0 }, { x1, L.y0 }, { x1, y1 }, { L.x0, y1 } };
		memcpy( g_Map.corner, c, sizeof( c ) );
	}
	g_Map.texW = NextPow2( g_Map.imgW );
	g_Map.texH = NextPow2( g_Map.imgH );
	g_Map.mode = MAP_LAYERS;
	CollectLayoutHeights();
	if ( !haveTxt || ( info.generated && !info.current && g_Map.havePicture ) )
		SaveClassicOverview( map, L, g_Map.havePicture ? &g_Map.picture : NULL );
}

static void EnsureMap()
{
	const char* level = gEngfuncs.pfnGetLevelName();
	if ( !level || !level[0] )
	{
		if ( g_Map.level[0] )
		{
			FreeMap();
			g_Map.level[0] = 0;
		}
		return;
	}
	if ( strcmp( level, g_Map.level ) )
		LoadMapFor( level );
}

// layout for the height the player is at (built maps only), re-rendered when the player changes floor
static void UpdateLayerPicture( float feetZ, float time )
{
	if ( g_Map.mode != MAP_LAYERS )
		return;
	if ( g_Map.layerBuilt && ( fabs( feetZ - g_Map.layerZ ) < 48.0f || time < g_Map.nextLayerBuild ) )
		return;
	// no floor between the old and the new height limit: the new layout would be identical to the one shown, so
	// skip drawing it again (up to 1024x1024 pixels) and uploading it, which used to cause a hitch on stairs/ramps
	if ( g_Map.layerBuilt && !LayoutHeightBetween( g_Map.layerZ + OVERVIEW_VIEWER_SLACK, feetZ + OVERVIEW_VIEWER_SLACK ) )
	{
		g_Map.layerZ = feetZ;
		g_Map.nextLayerBuild = time + 0.25f;
		return;
	}
	std::vector<unsigned char> rgba( (size_t)g_Map.imgW * g_Map.imgH * 4 );
	if ( g_Map.havePicture )
		Overview_RenderPicture( g_Map.picture, true, feetZ, rgba.data() );
	else
		Overview_Render( g_Map.layers, true, feetZ, rgba.data() );
	PadPremultiplied( rgba.data(), g_Map.imgW, g_Map.imgH, false, &g_Map.texW, &g_Map.texH, g_Map.upload );
	g_Map.layerZ = feetZ;
	g_Map.layerBuilt = true;
	g_Map.nextLayerBuild = time + 0.25f;
	g_Map.needUpload = true;
}

