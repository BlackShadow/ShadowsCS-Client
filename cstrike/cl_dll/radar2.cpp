static int NextPow2( int v )
{
	int p = 1;
	while ( p < v && p < 4096 )
		p <<= 1;
	return p;
}

static unsigned short U16( const unsigned char* p )
{
	return (unsigned short)( p[0] | ( p[1] << 8 ) );
}

static int I32( const unsigned char* p )
{
	return (int)( (unsigned int)p[0] | ( (unsigned int)p[1] << 8 ) | ( (unsigned int)p[2] << 16 ) | ( (unsigned int)p[3] << 24 ) );
}

// 8/24/32-bit uncompressed BMP -> RGBA (top row first)
static unsigned char* LoadBMP( const char* path, int* pw, int* ph )
{
	int len = 0;
	unsigned char* f = (unsigned char*)gEngfuncs.COM_LoadFile( (char*)path, 5, &len );
	if ( !f )
		return NULL;
	unsigned char* out = NULL;
	do
	{
		if ( len < 54 || f[0] != 'B' || f[1] != 'M' )
			break;
		const int offBits = I32( f + 10 ), biSize = I32( f + 14 ), w = I32( f + 18 ), hRaw = I32( f + 22 );
		const int bpp = U16( f + 28 ), compression = I32( f + 30 ), clrUsed = I32( f + 46 );
		const int h = hRaw < 0 ? -hRaw : hRaw;
		if ( w <= 0 || h <= 0 || w > 4096 || h > 4096 || compression != 0 || ( bpp != 8 && bpp != 24 && bpp != 32 ) )
			break;
		const int stride = ( ( w * bpp / 8 ) + 3 ) & ~3;
		if ( offBits < 0 || offBits > len || (long long)stride * h > (long long)len - offBits )
			break;
		const unsigned char* pal = f + 14 + biSize;
		const int palCount = bpp == 8 ? ( clrUsed > 0 && clrUsed <= 256 ? clrUsed : 256 ) : 0;
		if ( bpp == 8 && ( 14 + biSize < 14 || pal + palCount * 4 > f + len ) )
			break;
		out = (unsigned char*)malloc( (size_t)w * h * 4 );
		if ( !out )
			break;
		for ( int y = 0; y < h; y++ )
		{
			const unsigned char* row = f + offBits + (size_t)( hRaw < 0 ? y : h - 1 - y ) * stride;
			unsigned char* o = out + (size_t)y * w * 4;
			for ( int x = 0; x < w; x++, o += 4 )
			{
				if ( bpp == 8 )
				{
					const int i = row[x] < palCount ? row[x] : 0;
					o[0] = pal[i * 4 + 2];
					o[1] = pal[i * 4 + 1];
					o[2] = pal[i * 4 + 0];
				}
				else
				{
					const unsigned char* s = row + x * ( bpp / 8 );
					o[0] = s[2];
					o[1] = s[1];
					o[2] = s[0];
				}
				o[3] = 255;
			}
		}
		*pw = w;
		*ph = h;
	} while ( false );
	gEngfuncs.COM_FreeFile( f );
	return out;
}

// RGBA w x h -> premultiplied RGBA padded to power-of-two size; pure green (the overviews' "nothing") becomes clear
static void PadPremultiplied( const unsigned char* rgba, int w, int h, bool greenKey, int* texW, int* texH, std::vector<unsigned char>& out )
{
	*texW = NextPow2( w );
	*texH = NextPow2( h );
	out.assign( (size_t)*texW * *texH * 4, 0 );
	for ( int y = 0; y < h; y++ )
	{
		for ( int x = 0; x < w; x++ )
		{
			const unsigned char* s = rgba + ( (size_t)y * w + x ) * 4;
			unsigned char* d = &out[( (size_t)y * *texW + x ) * 4];
			int a = s[3];
			if ( greenKey && s[0] == 0 && s[1] == 255 && s[2] == 0 )
				a = 0;
			d[0] = (unsigned char)( s[0] * a / 255 );
			d[1] = (unsigned char)( s[1] * a / 255 );
			d[2] = (unsigned char)( s[2] * a / 255 );
			d[3] = (unsigned char)a;
		}
	}
}

// uploads a premultiplied RGBA picture with box-filtered mip levels to the bound texture
static void UploadMipmapped( const std::vector<unsigned char>& rgba, int w, int h )
{
	std::vector<unsigned char> level( rgba ), next;
	int lw = w, lh = h;
	for ( int l = 0;; l++ )
	{
		glTexImage2D( GL_TEXTURE_2D, l, GL_RGBA, lw, lh, 0, GL_RGBA, GL_UNSIGNED_BYTE, level.data() );
		if ( lw == 1 && lh == 1 )
			break;
		const int nw = lw > 1 ? lw / 2 : 1, nh = lh > 1 ? lh / 2 : 1;
		next.assign( (size_t)nw * nh * 4, 0 );
		for ( int y = 0; y < nh; y++ )
		{
			for ( int x = 0; x < nw; x++ )
			{
				for ( int c = 0; c < 4; c++ )
				{
					const int x0 = x * 2, y0 = y * 2;
					const int x1 = x0 + 1 < lw ? x0 + 1 : x0, y1 = y0 + 1 < lh ? y0 + 1 : y0;
					const int sum = level[( (size_t)y0 * lw + x0 ) * 4 + c] + level[( (size_t)y0 * lw + x1 ) * 4 + c] +
					                level[( (size_t)y1 * lw + x0 ) * 4 + c] + level[( (size_t)y1 * lw + x1 ) * 4 + c];
					next[( (size_t)y * nw + x ) * 4 + c] = (unsigned char)( ( sum + 2 ) / 4 );
				}
			}
		}
		level.swap( next );
		lw = nw;
		lh = nh;
	}
	glTexParameteri( GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR );
	glTexParameteri( GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR );
	glTexParameteri( GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE );
	glTexParameteri( GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE );
}

