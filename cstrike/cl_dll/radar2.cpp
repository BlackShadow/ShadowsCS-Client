// the textures waiting from the loaders, uploaded on the GL side; the texture binding is put back afterwards (the
// engine remembers which texture it bound last)
static void UploadPending()
{
	const bool map = g_Map.needUpload && !g_Map.upload.empty();
	const bool c4 = !g_C4.uploaded && !g_C4.rgba.empty();
	const bool hostage = !g_Hostage.uploaded && !g_Hostage.rgba.empty();
	if ( !map && !c4 && !hostage )
		return;
	glPushAttrib( GL_TEXTURE_BIT );
	if ( map )
	{
		glBindTexture( GL_TEXTURE_2D, kMapTex );
		UploadMipmapped( g_Map.upload, g_Map.texW, g_Map.texH );
		g_Map.needUpload = false;
		g_Map.uploaded = true;
		if ( g_Map.mode == MAP_IMAGE )
		{
			g_Map.upload.clear();
			g_Map.upload.shrink_to_fit();
		}
	}
	if ( c4 )
	{
		glBindTexture( GL_TEXTURE_2D, kC4Tex );
		UploadMipmapped( g_C4.rgba, g_C4.texW, g_C4.texH );
		g_C4.uploaded = true;
	}
	if ( hostage )
	{
		glBindTexture( GL_TEXTURE_2D, kHostageTex );
		UploadMipmapped( g_Hostage.rgba, g_Hostage.texW, g_Hostage.texH );
		g_Hostage.uploaded = true;
	}
	glPopAttrib();
}

static Radar2Picture Picture( GLuint texture, bool ready, int w, int h, int texW, int texH )
{
	Radar2Picture picture;
	picture.texture = ready ? texture : 0;
	picture.w = w;
	picture.h = h;
	picture.texW = texW;
	picture.texH = texH;
	return picture;
}

void Radar2_GetRect( int* x, int* y, int* size )
{
	const int S = gHUD.m_iHudScale > 0 ? gHUD.m_iHudScale : 1;
	float s = cl_radar_size ? cl_radar_size->value : 150.0f;
	if ( s < 64.0f )
		s = 64.0f;
	if ( s > 400.0f )
		s = 400.0f;
	*x = 4 * S;
	*y = 4 * S;
	*size = (int)( s * S );
}

int Radar2_Draw( const float origin[3], const float angles[3], const Radar2Blip* blips, int numBlips, float time )
{
	EnsureMap();
	LoadHudIcon( g_C4, "c4" );
	LoadHudIcon( g_Hostage, "hostage" );
	// The height a built layout is cut at: the floor under the player's feet (crouched: 18 below the middle, standing:
	// 36), kept while in the air. It used to follow the middle of the player every frame, so a jump or a duck moved the
	// cut and crates and ledges popped in and out of the radar. In the air for over a second (ladders, long drops), it
	// follows the player again.
	static float s_groundFeet = 0.0f, s_leftGround = 0.0f;
	static bool s_haveGround = false;
	const float feetNow = origin[2] - ( ( g_iPlayerFlags & FL_DUCKING ) ? 18.0f : 36.0f );
	if ( ( g_iPlayerFlags & FL_ONGROUND ) || !s_haveGround || time < s_leftGround )
	{
		s_groundFeet = feetNow;
		s_haveGround = true;
		s_leftGround = time;
	}
	else if ( time - s_leftGround > 1.0f )
		s_groundFeet = feetNow;
	UpdateLayerPicture( s_groundFeet, time );

	const int S = gHUD.m_iHudScale > 0 ? gHUD.m_iHudScale : 1;
	int x0, y0, size;
	Radar2_GetRect( &x0, &y0, &size );
	float range = cl_radar_range ? cl_radar_range->value : 1000.0f;
	if ( range < 300.0f )
		range = 300.0f;
	if ( range > 8000.0f )
		range = 8000.0f;
	float mapAlpha = cl_radar_alpha ? cl_radar_alpha->value : RADAR_MAP_OPACITY_DEFAULT_VALUE;
	mapAlpha = mapAlpha < 0.0f ? 0.0f : mapAlpha > 1.0f ? 1.0f : mapAlpha;

	const int W = ScreenWidth, H = ScreenHeight;
	if ( W <= 0 || H <= 0 )
		return y0 + size;
	UploadPending();

	Radar2Square radar;
	memset( &radar, 0, sizeof( radar ) );
	radar.x0 = (float)x0;
	radar.y0 = (float)y0;
	radar.size = (float)size;
	radar.unit = (float)S;
	radar.range = range;
	radar.mapAlpha = mapAlpha;
	radar.rotate = !cl_radar_rotate || cl_radar_rotate->value != 0.0f;
	radar.fovDegrees = (float)( gHUD.m_iFOV > 0 ? gHUD.m_iFOV : 90 );
	radar.screenWide = W;
	radar.screenTall = H;
	radar.origin = origin;
	radar.angles = angles;
	radar.blips = blips;
	radar.numBlips = numBlips;
	radar.time = time;
	radar.map = Picture( kMapTex, g_Map.uploaded && g_Map.mode != MAP_NONE, g_Map.imgW, g_Map.imgH, g_Map.texW, g_Map.texH );
	memcpy( radar.mapCorner, g_Map.corner, sizeof( radar.mapCorner ) );
	radar.c4 = Picture( kC4Tex, g_C4.uploaded, g_C4.w, g_C4.h, g_C4.texW, g_C4.texH );
	radar.hostage = Picture( kHostageTex, g_Hostage.uploaded, g_Hostage.w, g_Hostage.h, g_Hostage.texW, g_Hostage.texH );
	Radar2_DrawSquare( radar );
	return y0 + size;
}

// ---------------------------------------------------------------------------------------------------------------
// the Advanced window's radar preview
//
// Just the radar, filling the box, drawn by the HUD's own code. On it a small Terrorist team in de_dust2's mid (the
// official overview): you walking back and forth and looking around,
// a teammate down in the tunnel (below you), one up in the corridor, the bomb carrier on the right, and where a
// teammate died. The classic round radar shows the same team with the HUD's round radar picture for your HUD size.
// ---------------------------------------------------------------------------------------------------------------

static const GLuint kPreviewMapTex = 0x52414404u;
static const GLuint kPreviewRoundTex = 0x52414406u;
static const GLuint kPreviewRoundOpaqueTex = 0x52414407u;

struct PreviewTexture
{
	int w, h, texW, texH;
	std::vector<unsigned char> upload;	// waiting for the GL side
	bool uploaded;
};

struct PreviewData
{
	bool tried;
	int roundTier;				// the HUD tier the round radar picture was loaded for
	PreviewTexture map;			// de_dust2's overview (premultiplied, green cleared)
	float corner[4][2];
	PreviewTexture round;		// the round radar: additive picture
	PreviewTexture roundOpaque;	// and the solid one with holes (cl_radartype 1)
};
static PreviewData g_Preview;

// frame 0 of a sprite as RGBA; holes: palette index 255 is see-through (alpha-tested sprites)
static bool LoadSpriteRGBA( const char* path, bool holes, PreviewTexture& out )
{
	int len = 0;
	unsigned char* f = (unsigned char*)gEngfuncs.COM_LoadFile( (char*)path, 5, &len );
	if ( !f )
		return false;
	bool ok = false;
	do
	{
		if ( len < 42 || memcmp( f, "IDSP", 4 ) || I32( f + 4 ) != 2 )
			break;
		const int palCount = (short)U16( f + 40 );
		if ( palCount < 1 || palCount > 256 || 42 + palCount * 3 + 20 > len )
			break;
		const unsigned char* pal = f + 42;
		const unsigned char* frame = pal + palCount * 3;
		const int fw = I32( frame + 12 ), fh = I32( frame + 16 );
		const unsigned char* pix = frame + 20;
		if ( I32( frame ) != 0 || fw <= 0 || fh <= 0 || fw > 2048 || fh > 2048 || (long long)fw * fh > ( f + len ) - pix )
			break;
		out.w = fw;
		out.h = fh;
		out.texW = NextPow2( fw );
		out.texH = NextPow2( fh );
		out.upload.assign( (size_t)out.texW * out.texH * 4, 0 );
		for ( int y = 0; y < fh; y++ )
		{
			for ( int x = 0; x < fw; x++ )
			{
				const int index = pix[(size_t)y * fw + x];
				const unsigned char* c = pal + ( index < palCount ? index : 0 ) * 3;
				unsigned char* d = &out.upload[( (size_t)y * out.texW + x ) * 4];
				d[0] = c[0];
				d[1] = c[1];
				d[2] = c[2];
				d[3] = holes && index == 255 ? 0 : 255;
			}
		}
		out.uploaded = false;
		ok = true;
	} while ( false );
	gEngfuncs.COM_FreeFile( f );
	return ok;
}

static void LoadPreviewRound( int tier )
{
	g_Preview.roundTier = tier;
	char additive[64], opaque[64];
	snprintf( additive, sizeof( additive ), "sprites/cs%d/radar.spr", tier );
	snprintf( opaque, sizeof( opaque ), "sprites/cs%d/radaropaque.spr", tier );
	if ( tier <= 640 || !LoadSpriteRGBA( additive, false, g_Preview.round ) )
		LoadSpriteRGBA( "sprites/radar640.spr", false, g_Preview.round );
	if ( tier <= 640 || !LoadSpriteRGBA( opaque, true, g_Preview.roundOpaque ) )
		LoadSpriteRGBA( "sprites/radaropaque640.spr", true, g_Preview.roundOpaque );
}

static void LoadPreview()
{
	if ( g_Preview.tried )
		return;
	g_Preview.tried = true;

	// de_dust2's official overview
	OverviewInfo info;
	if ( ReadOverviewTxt( "de_dust2", info ) && !info.generated && info.image[0] )
	{
		int w = 0, h = 0;
		unsigned char* rgba = LoadBMP( info.image, &w, &h );
		if ( rgba )
		{
			PadPremultiplied( rgba, w, h, true, &g_Preview.map.texW, &g_Preview.map.texH, g_Preview.map.upload );
			free( rgba );
			g_Preview.map.w = w;
			g_Preview.map.h = h;
			OverviewCorners( info, g_Preview.corner );
		}
	}
}

static void UploadPreviewTexture( PreviewTexture& texture, GLuint name )
{
	if ( texture.uploaded || texture.upload.empty() )
		return;
	glBindTexture( GL_TEXTURE_2D, name );
	UploadMipmapped( texture.upload, texture.texW, texture.texH );
	texture.upload.clear();
	texture.upload.shrink_to_fit();
	texture.uploaded = true;
}

static Radar2Picture PreviewPicture( const PreviewTexture& texture, GLuint name )
{
	return Picture( name, texture.uploaded, texture.w, texture.h, texture.texW, texture.texH );
}

void Radar2_DrawPreview( int x, int y, int box, int screenWide, int screenTall, bool square, float sizeSetting, float rangeSetting,
	float alphaSetting, bool rotate, float time )
{
	if ( box <= 0 || screenWide <= 0 || screenTall <= 0 )
		return;
	LoadPreview();
	LoadHudIcon( g_C4, "c4" );
	LoadHudIcon( g_Hostage, "hostage" );
	const int tier = gHUD.m_iRes > 640 ? gHUD.m_iRes : 640;
	if ( g_Preview.roundTier != tier )
		LoadPreviewRound( tier );

	// GL side: the textures waiting (the binding is put back afterwards)
	UploadPending();
	glPushAttrib( GL_TEXTURE_BIT );
	UploadPreviewTexture( g_Preview.map, kPreviewMapTex );
	UploadPreviewTexture( g_Preview.round, kPreviewRoundTex );
	UploadPreviewTexture( g_Preview.roundOpaque, kPreviewRoundOpaqueTex );
	glPopAttrib();

	Radar2Preview preview;
	memset( &preview, 0, sizeof( preview ) );
	preview.x = x;
	preview.y = y;
	preview.box = box;
	preview.screenWide = screenWide;
	preview.screenTall = screenTall;
	preview.square = square;
	preview.size = sizeSetting;
	preview.range = rangeSetting;
	preview.mapAlpha = alphaSetting;
	preview.rotate = rotate;
	preview.opaque = gEngfuncs.pfnGetCvarFloat( (char*)"cl_radartype" ) != 0.0f;
	preview.time = time;
	preview.map = PreviewPicture( g_Preview.map, kPreviewMapTex );
	memcpy( preview.mapCorner, g_Preview.corner, sizeof( preview.mapCorner ) );
	preview.c4 = Picture( kC4Tex, g_C4.uploaded, g_C4.w, g_C4.h, g_C4.texW, g_C4.texH );
	preview.hostage = Picture( kHostageTex, g_Hostage.uploaded, g_Hostage.w, g_Hostage.h, g_Hostage.texW, g_Hostage.texH );
	preview.round = PreviewPicture( g_Preview.round, kPreviewRoundTex );
	preview.roundOpaque = PreviewPicture( g_Preview.roundOpaque, kPreviewRoundOpaqueTex );
	Radar2_DrawPreviewBox( preview );
}

